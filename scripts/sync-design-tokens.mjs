import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = JSON.parse(readFileSync(new URL('../docs/design/tokens.json', import.meta.url), 'utf8'));
const target = new URL('../web/src/styles/tokens.css', import.meta.url);
const kebab = value => value.replace(/[A-Z]/g, match => `-${match.toLowerCase()}`);
const groups = ['color', 'font', 'layout', 'typography', 'motion'];
const declarations = groups.flatMap(group => Object.entries(source[group])
  .filter(([key]) => !['source', 'reducedMotion'].includes(key))
  .map(([key, value]) => `  --${group}-${kebab(key)}: ${value};`));
const css = `/* Generated from docs/design/tokens.json; do not edit this file by hand. */\n:root {\n${declarations.join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) throw new Error('Design tokens are out of sync. Run npm run tokens:sync.');
  console.log('Design-token parity passed.');
} else {
  writeFileSync(target, css);
  console.log(`Generated ${fileURLToPath(target)}`);
}
